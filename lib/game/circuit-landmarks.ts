export type LandmarkKindId = (typeof LANDMARK_KIND_IDS)[number];

export interface CircuitLandmarkDef {
  name: string;
  kind: LandmarkKindId;
  color: string;
  accent: string;
  height: number;
}

type Entry = [string, LandmarkKindId, number];

function pack(
  entries: Entry[],
  palettes: Array<[string, string]>,
): CircuitLandmarkDef[] {
  return entries.map(([name, kind, height], i) => ({
    name,
    kind,
    color: palettes[i % palettes.length][0],
    accent: palettes[i % palettes.length][1],
    height,
  }));
}

