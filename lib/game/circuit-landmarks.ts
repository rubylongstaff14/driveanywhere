export const CIRCUIT_LANDMARKS: Record<string, CircuitLandmarkDef[]> = {
  "westminster-sprint": WESTMINSTER,
  "embankment-run": EMBANKMENT,
  "canary-wharf-loop": CANARY,
  "egypt-pyramids": EGYPT,
  "dubai-marina-circuit": DUBAI,
  "new-york-harbor-circuit": NYC,
  "tokyo-drift-circuit": TOKYO,
  "alps-mountain-pass": ALPS,
  "rio-coast-circuit": RIO,
};

const BY_NAME = new Map<string, CircuitLandmarkDef>();
for (const list of Object.values(CIRCUIT_LANDMARKS)) {
  for (const item of list) BY_NAME.set(item.name.toLowerCase(), item);
}

export function circuitLandmarksFor(slug: string): CircuitLandmarkDef[] {
  const base = CIRCUIT_LANDMARKS[slug] ?? [];
  const target = 90;
  if (base.length >= target) return base;
  const kinds = LANDMARK_KIND_IDS.filter(
    (k) => !["ferris", "pyramid", "sphinx", "statue"].includes(k),
  );
  const palettes =
    slug.includes("dubai")
      ? DUBAI_PAL
      : slug.includes("egypt")
        ? EGYPT_PAL
        : slug.includes("york")
          ? NYC_PAL
          : slug.includes("tokyo")
            ? TOKYO_PAL
            : slug.includes("alps")
              ? ALPS_PAL
              : slug.includes("rio")
                ? RIO_PAL
                : LONDON_PAL;
  const extras: CircuitLandmarkDef[] = [];
  for (let i = base.length; i < target; i++) {
    const kind = kinds[i % kinds.length];
    const [color, accent] = palettes[i % palettes.length];
    extras.push({
      name: `${slug.split("-")[0]} Streetscape ${i + 1}`,
      kind,
      color,
      accent,
      height: 28 + ((i * 7) % 90),
    });
  }
  return [...base, ...extras];
}

export function circuitLandmarkByName(name?: string): CircuitLandmarkDef | null {
  if (!name) return null;
  return BY_NAME.get(name.toLowerCase()) ?? null;
}
